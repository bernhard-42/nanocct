"""Build the cadquery-ocp-novtk 8.0.1.0.0+shim compatibility wheel: `import OCP.*` on top of nanocct. Stdlib only.

    python shim/build_wheel.py [out_dir]          (default: shim/dist; `make shim` writes to dist/)

The package is generated by shim/generate.py (OCP/__init__.py, OCP/_patches.py, one OCP/<pkg>/__init__.py per OCP
module) plus the runtime helpers OCP/_rt.py. Generation reads nanocct's own signatures, so nanocct must be importable
by the interpreter that runs this -- the development venv with the staged build.
"""
import base64
import hashlib
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).parent
# The local version label "+shim" is what `pip list` shows next to the name, so an installed shim is told apart from
# the real cadquery-ocp-novtk at a glance. PEP 440 ignores a local label when matching a version without one, so
# build123d's unpatched "cadquery-ocp-novtk >= 8.0, < 8.1" is still satisfied (uv, 2026-09-28); a distribution of
# another name is not, and uv then installs the real package next to it, both writing OCP/. A local test vehicle,
# never uploaded (PyPI refuses local versions anyway).
NAME, DIST, VERSION = "cadquery-ocp-novtk", "cadquery_ocp_novtk", "8.0.1.0.0+shim"
REQUIRES = ["nanocct>=8.0.1,<8.0.2", "cadquery-ocp-proxy==8.0.1.0.0"]   # any nanocct for OCCT 8.0.1 (8.0.1.0, fixes 8.0.1.x)
OCP_VERSION = "8.0.1.0"      # OCP.__version__ of the real package

METADATA = f"""Metadata-Version: 2.1
Name: {NAME}
Version: {VERSION}
Summary: OCP (cadquery-ocp 8.0.1) import compatibility on top of nanocct
License: Apache-2.0
Requires-Python: >=3.12
""" + "".join(f"Requires-Dist: {r}\n" for r in REQUIRES)

WHEEL = """Wheel-Version: 1.0
Generator: nanocct shim/build_wheel.py
Root-Is-Purelib: true
Tag: py3-none-any
"""


def files() -> dict[str, bytes]:
    sys.path.insert(0, str(HERE))
    import generate                                      # imports nanocct.all
    out = {path: text.encode() for path, text in generate.main().items()}
    out["OCP/_rt.py"] = (HERE / "OCP" / "_rt.py").read_bytes()
    return out


def digest(data: bytes) -> str:
    return "sha256=" + base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode()


def main() -> None:
    out_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "dist"
    out_dir.mkdir(parents=True, exist_ok=True)
    info = f"{DIST}-{VERSION}.dist-info"
    content = files()
    content[f"{info}/METADATA"] = METADATA.encode()
    content[f"{info}/WHEEL"] = WHEEL.encode()
    record = "".join(f"{p},{digest(d)},{len(d)}\n" for p, d in content.items()) + f"{info}/RECORD,,\n"
    content[f"{info}/RECORD"] = record.encode()
    whl = out_dir / f"{DIST}-{VERSION}-py3-none-any.whl"
    with zipfile.ZipFile(whl, "w", zipfile.ZIP_DEFLATED) as z:
        for path, data in content.items():
            z.writestr(path, data)
    print(f"{whl} ({whl.stat().st_size // 1024} KB, {len(content)} files)")


if __name__ == "__main__":
    main()
